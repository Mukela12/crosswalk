"""Generate the reference-data migration from specs/controls.json.

Usage: python3 tools/gen_reference_sql.py > api/src/main/resources/db/migration/V3__reference_data.sql
"""
import json
import pathlib
import sys

root = pathlib.Path(__file__).resolve().parent.parent
data = json.loads((root / "specs" / "controls.json").read_text())


def q(s):
    return "'" + s.replace("'", "''") + "'"


out = ["-- Generated by tools/gen_reference_sql.py from specs/controls.json. Do not edit by hand.", ""]
fw_ids = {}
out.append("insert into framework (id, code, name, version) values")
rows = []
for i, f in enumerate(data["frameworks"], start=1):
    fw_ids[f["code"]] = i
    rows.append(f"    ({i}, {q(f['code'])}, {q(f['name'])}, {q(f['version'])})")
out.append(",\n".join(rows) + ";\n")

req_ids = {}
rows = []
for i, r in enumerate(data["requirements"], start=1):
    req_ids[(r["framework"], r["ref"])] = i
    rows.append(f"    ({i}, {fw_ids[r['framework']]}, {q(r['ref'])}, {q(r['title'])})")
out.append("insert into requirement (id, framework_id, ref, title) values")
out.append(",\n".join(rows) + ";\n")

rows, maps, samples = [], [], []
for i, c in enumerate(data["controls"], start=1):
    rows.append(f"    ({i}, {q(c['code'])}, {q(c['domain'])}, {q(c['title'])}, {q(c['description'])})")
    for fw, refs in c["maps"].items():
        for ref in refs:
            maps.append(f"    ({i}, {req_ids[(fw, ref)]})")
    for n, title in enumerate(c["evidence"], start=1):
        samples.append(f"    ({i}, {n}, {q(title)})")
out.append("insert into control (id, code, domain, title, description) values")
out.append(",\n".join(rows) + ";\n")
out.append("insert into control_requirement (control_id, requirement_id) values")
out.append(",\n".join(maps) + ";\n")
out.append("insert into control_sample_evidence (control_id, ord, title) values")
out.append(",\n".join(samples) + ";")
sys.stdout.write("\n".join(out) + "\n")
